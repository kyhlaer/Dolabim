    val ALL_LOOKS: List<LookbookItem> = MEN_LOOKS + WOMEN_LOOKS

    fun looksForGender(gender: LookbookGender): List<LookbookItem> = when (gender) {
        LookbookGender.MEN -> MEN_LOOKS
        LookbookGender.WOMEN -> WOMEN_LOOKS
    }

    fun filterLooks(
        looks: List<LookbookItem>,
        category: InspirationCategory = InspirationCategory.ALL,
        season: Season? = null
    ): List<LookbookItem> = looks.filter { item ->
        val catOk = category == InspirationCategory.ALL || item.category == category
        val seaOk = when (season) {
            null -> true
            Season.ALL -> item.season == Season.ALL
            else -> item.season == season || item.season == Season.ALL
        }
        catOk && seaOk
    }

    fun computeLookSkinToneMatch(
        paletteColors: List<GarmentColor>,
        flatteringColors: Set<GarmentColor>,
        avoidColors: Set<GarmentColor> = emptySet()
    ): Int? {
        if (paletteColors.isEmpty() || flatteringColors.isEmpty()) return null
        val flatGroups = flatteringColors.map { it.hueGroup }.toSet()
        var score = 68
        for (color in paletteColors) {
            when {
                color in flatteringColors -> score += 11
                color.hueGroup in flatGroups -> score += 6
                color.isNeutral -> score += 4
            }
            if (color in avoidColors) score -= 10
        }
        return score.coerceIn(45, 99)
    }

    private fun interleaveLookbookCategories(items: List<LookbookItem>): List<LookbookItem> {
        val order = listOf(
            InspirationCategory.SMART_CASUAL,
            InspirationCategory.MINIMALIST,
            InspirationCategory.STREETWEAR,
            InspirationCategory.VINTAGE_Y2K,
            InspirationCategory.SPORTY_CHIC,
            InspirationCategory.EVENING_DATE
        )
        val buckets = order.associateWith { cat -> ArrayDeque(items.filter { it.category == cat }) }
        val mixed = ArrayList<LookbookItem>(items.size)
        while (mixed.size < items.size) {
            var added = false
            for (cat in order) {
                val q = buckets[cat]
                if (q != null && q.isNotEmpty()) {
                    mixed.add(q.removeFirst())
                    added = true
                }
            }
            if (!added) break
        }
        return mixed
    }
